// Typed Ansible job wire shapes (#760).

// JobAttributes: the always-null and conditionally-set members mirror the map builder exactly.
// SliceGroupID, RunnerID, StartedAt and FinishedAt are pointers because the old map emitted
// them as null until set - present either way.
type JobAttributes struct {
	Name             string                  `json:"name"`
	JobType          models.AnsibleJobType   `json:"job-type"`
	Status           models.AnsibleJobStatus `json:"status"`
	ExtraVars        models.JobExtraVars     `json:"extra-vars"`
	Limit            string                  `json:"limit"`
	Tags             string                  `json:"tags"`
	SkipTags         string                  `json:"skip-tags"`
	Verbosity        int                     `json:"verbosity"`
	Forks            int                     `json:"forks"`
	BecomeEnabled    bool                    `json:"become-enabled"`
	SliceNumber      int                     `json:"slice-number"`
	SliceCount       int                     `json:"slice-count"`
	SliceGroupID     *string                 `json:"slice-group-id"`
	RunnerID         *string                 `json:"runner-id"`
	DiffMode         bool                    `json:"diff-mode"`
	AnsibleVersion   string                  `json:"ansible-version"`
	ExitCode         *int                    `json:"exit-code"`
	ErrorMessage     string                  `json:"error-message"`
	StartedAt        *string                 `json:"started-at"`
	FinishedAt       *string                 `json:"finished-at"`
	HostsTotal       int                     `json:"hosts-total"`
	HostsOk          int                     `json:"hosts-ok"`
	HostsChanged     int                     `json:"hosts-changed"`
	HostsFailed      int                     `json:"hosts-failed"`
	HostsUnreachable int                     `json:"hosts-unreachable"`
	HostsSkipped     int                     `json:"hosts-skipped"`
	HostsRescued     int                     `json:"hosts-rescued"`
	HostsIgnored     int                     `json:"hosts-ignored"`
	HasWarnings      bool                    `json:"has-warnings"`
	WarningsCount    int                     `json:"warnings-count"`
	CreatedAt        string                  `json:"created-at"`
	UpdatedAt        string                  `json:"updated-at"`

	// Ad hoc jobs only (transient playbook generated by the runner).
	Module     string `json:"module,omitempty"`
	ModuleArgs string `json:"module-args,omitempty"`

	AgentPoolName string `json:"agent-pool-name,omitempty"`
	RunnerName    string `json:"runner-name,omitempty"`
}


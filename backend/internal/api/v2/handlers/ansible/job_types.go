// EventAttributes is a full ansible-job-events resource. EventData is the runner's own payload,
// forwarded (or projected) verbatim: Stackweaver does not own Ansible's event schema, so it is
// deliberately a map - the same reasoning as the Zitadel passthroughs in #755.
type EventAttributes struct {
	Counter   int                 `json:"counter"`
	EventType string              `json:"event-type"`
	EventData models.JobExtraVars `json:"event-data"`
	Host      string              `json:"host"`
	Task      string              `json:"task"`
	Play      string              `json:"play"`
	Role      string              `json:"role"`
	Stdout    string              `json:"stdout"`
	Stderr    string              `json:"stderr"`
	Changed   bool                `json:"changed"`
	Failed    bool                `json:"failed"`
	Skipped   bool                `json:"skipped"`
	Timestamp string              `json:"timestamp"`
	CreatedAt string              `json:"created-at"`
	Summary   bool                `json:"summary,omitempty"`
}

// EventRelationships points an event at its job.
type EventRelationships struct {
	Job jsonapi.Relationship `json:"job"`
}

// Typed workflow wire shapes (#760). Nodes and edges ride INLINE as full resources inside the
// workflow's relationships on the show endpoint, so those members are typed as slices of the
// full resource rather than bare identifiers - preserved from the map-based decoration.

// WorkflowAttributes: timestamps are time.Time here because the map builder emitted the raw
// values (RFC3339 with nanoseconds), unlike the second-precision strings elsewhere.
type WorkflowAttributes struct {
	Name                 string    `json:"name"`
	Description          string    `json:"description"`
	AllowSimultaneous    bool      `json:"allow-simultaneous"`
	AskVariablesOnLaunch bool      `json:"ask-variables-on-launch"`
	AskInventoryOnLaunch bool      `json:"ask-inventory-on-launch"`
	AskLimitOnLaunch     bool      `json:"ask-limit-on-launch"`
	ExtraVars            string    `json:"extra-vars"`
	Limit                string    `json:"limit"`
	SurveyEnabled        bool      `json:"survey-enabled"`
	CreatedAt            time.Time `json:"created-at"`
	UpdatedAt            time.Time `json:"updated-at"`
}

// WorkflowNodesRelationship carries full node resources inline.
type WorkflowNodesRelationship struct {
	Data []jsonapi.Resource[WorkflowNodeAttributes] `json:"data"`
}

// WorkflowEdgesRelationship carries full edge resources inline.
type WorkflowEdgesRelationship struct {
	Data []jsonapi.Resource[WorkflowEdgeAttributes] `json:"data"`
}

// WorkflowRelationships: organization always; project/inventory per wiring; nodes/edges only
// on the show endpoint, added by the handler after the base builder.
type WorkflowRelationships struct {
	Organization jsonapi.Relationship       `json:"organization"`
	Project      *jsonapi.Relationship      `json:"project,omitempty"`
	Inventory    *jsonapi.Relationship      `json:"inventory,omitempty"`
	Nodes        *WorkflowNodesRelationship `json:"nodes,omitempty"`
	Edges        *WorkflowEdgesRelationship `json:"edges,omitempty"`
}

// WorkflowResource has mutable relationships so the show handler can attach nodes and edges.
type WorkflowResource struct {
	ID            string                 `json:"id"`
	Type          string                 `json:"type"`
	Attributes    WorkflowAttributes     `json:"attributes"`
	Relationships *WorkflowRelationships `json:"relationships"`
}

